from collections import deque

def largest_safe_zone(grid, N, M, T):
    visited = set()
    max_size = 0
    
    for r in range(N):
        for c in range(M):
            if grid[r][c] < T and (r, c) not in visited:
                # Start BFS for this island
                current_size = 0
                queue = deque([(r, c)])
                visited.add((r, c))
                
                while queue:
                    curr_r, curr_c = queue.popleft()
                    current_size += 1
                    
                    # Check 4 neighbors
                    for dr, dc in [(-1,0), (1,0), (0,-1), (0,1)]:
                        nr, nc = curr_r + dr, curr_c + dc
                        if 0 <= nr < N and 0 <= nc < M and (nr, nc) not in visited:
                            if grid[nr][nc] < T:
                                visited.add((nr, nc))
                                queue.append((nr, nc))
                                
                max_size = max(max_size, current_size)
    return max_size

