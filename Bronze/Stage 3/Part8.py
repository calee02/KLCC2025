# 📌 Part 8 – Count of Survivors & Infected Settlements

"""
Task: Output a list [survivors, infected] counting positive numbers (survivors) and negative numbers (infected). 
Ignore 0s (abandoned sites).

Rule: Use two counters—one for positive numbers and one for negative numbers.
"""

def count_survivor_and_infectors(lst):
    survivor = 0
    infected = 0

    for num in lst:
        if num > 0:
            survivor += 1
        if num < 0: 
            infected += 1
    
    return [survivor, infected]

