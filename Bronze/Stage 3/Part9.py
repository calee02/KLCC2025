# 📌 Part 9 – Total Salvage Value with Bonus

"""
Task: 
- The 1st number is the base value. 
- Every next number adds a bonus only if it is strictly greater than the number immediately before it.

 Rule: 
 - Always keep the 1st number. 
 - For all other numbers, compare each with its left neighbor 
 — if it's bigger, add it to your total!
 """

def total_salvage_value(arr):
    total = arr[0]  # 1st number is Base value
    for i in range(1, len(arr)): # start from second number, ends at last number
        if arr[i] > arr[i - 1]:
            total += arr[i]
    return total

