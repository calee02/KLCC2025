# 📌 Part 11 – Antidote Maximum Toxicity Product

"""
Task: 
Pick two numbers in a list whose product (multiplication) is as large as possible.

Rule: 
- Sort the list! 
- The highest product is either the two largest positive numbers (at the end) OR 
two large negative numbers (at the beginning, since negative $\times$ negative = positive!).
"""

def max_toxicity_product(lst):
    s = sorted(lst)
    return max(s[0] * s[1], s[-1]*s[-2])

