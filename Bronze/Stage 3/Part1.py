# Part 1 - Total Salvageable Supply Count

"""
Task: Output the total number of salvageable supplies. 

Given a list of positive (salvageable) and negative (spoiled) supply counts, 
output the total sum of only the salvageable (positive) supplies.

Rule: Skip all negative numbers! 
Loop through the list and only add up numbers strictly greater than 0
"""

def total_salvageable(lst):
    sum = 0

    for num in lst:
        if num > 0:
            sum += num
    
    return sum

