"""
Task: You have a list containing the strongholds that each survivor is at, where each stronghold is
represented by its ID. --- this means it is unique, we can check using set, as the number in set in not duplicate 
Count the number of strongholds. 

Rule: 
Throw the list into a set() 
(which automatically deletes all duplicate copies!), then check len().
"""

def count_unique_strongholds(lst):
    return(len(set(lst)))

