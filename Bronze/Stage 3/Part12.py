# 📌 Part 12 – Most Frequent Resource ID (Mode)

"""
Task: Find the resource ID that appears most often. 
If there's a tie, return the one that appeared first in the list.

Rule: 
- Count frequencies using collections.Counter
- find the highest count
- pick the first item in the original list that hits that count
"""

from collections import Counter

def most_frequent_resource(lst):
    counts = Counter(lst)
    # print("This is counts: ", counts)

    max_count = max(counts.values())
    # print(max_count)

    for item in lst:
        if counts[item] == max_count:
            return item

